export function getCalculatorMaterials(catalog = MATERIALS_CATALOG) {
  return catalog.filter(m => m.is_calculator_item !== false)
}

export function getDefaultMaterialForCategory(categoryKey, packageKey = 'standard', catalog = MATERIALS_CATALOG) {
  const calcItems = getCalculatorMaterials(catalog).filter(m => m.category === categoryKey)
  return (
    calcItems.find(m => m.tier === packageKey) ||
    calcItems.find(m => m.tier === 'standard') ||
    calcItems[0] ||
    null
  )
}
